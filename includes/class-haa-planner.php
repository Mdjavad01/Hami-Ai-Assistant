	 * Reading and moving rows
	 * ---------------------------------------------------------------- */
	/**
	 * @param string $status Status filter, '' for all.
	 * @param int    $limit  Row cap.
	 * @return array
	 */
	public static function rows( $status = '', $limit = 50 ) {
		global $wpdb;
		$table = self::table();
		if ( '' !== $status && in_array( $status, self::STATUSES, true ) ) {
			$rows = $wpdb->get_results( $wpdb->prepare( "SELECT * FROM $table WHERE status = %s ORDER BY priority DESC, id DESC LIMIT %d", $status, (int) $limit ), ARRAY_A ); // phpcs:ignore WordPress.DB
		} else {
			$rows = $wpdb->get_results( "SELECT * FROM $table ORDER BY priority DESC, id DESC LIMIT " . (int) $limit, ARRAY_A ); // phpcs:ignore WordPress.DB
		}
		return array_map(
			array( __CLASS__, 'hydrate' ),
			(array) $rows
		);
	}

	/**
	 * Turn one raw topics row into the shape every caller expects.
	 *
	 * Both rows() and row() must go through here. When the JSON columns were
	 * decoded in only one of them, a caller of row() got the brief back as a
	 * string — and (array) on a string silently yields [0 => text], so the
	 * pipeline thought there was no outline and paid for a model call again.
	 *
	 * @param array $r Raw associative row.
	 * @return array
	 */
	private static function hydrate( $r ) {
		return array(
			'id'         => (int) $r['id'],
			'title'      => (string) $r['title'],
			'keyword'    => (string) $r['keyword'],
			'secondary'  => (string) $r['secondary'],
			'intent'     => (string) $r['intent'],
			'priority'   => (int) $r['priority'],
			'reason'     => (string) $r['reason'],
			'status'     => (string) $r['status'],
			'source'     => (string) $r['source'],
			'post_id'    => (int) $r['post_id'],
			'job_id'     => (int) $r['job_id'],
			'tokens_est' => (int) $r['tokens_est'],
			'stage'      => (string) ( $r['stage'] ?? '' ),
			'brief'      => (array) self::decode( $r['brief'] ?? null ),
			'notes'      => (array) self::decode( $r['notes'] ?? null ),
			'error'      => (string) ( $r['error'] ?? '' ),
			'created'    => (string) $r['created'],
		);
	}

	/**
	 * JSON column reader that never throws on legacy/empty values.
	 *
	 * @param mixed $raw Column value.
	 * @return array
	 */
	private static function decode( $raw ) {
		if ( is_array( $raw ) ) {
			return $raw;
		}
		$raw = (string) $raw;
		if ( '' === $raw ) {
			return array();
		}
		$json = json_decode( $raw, true );
		return is_array( $json ) ? $json : array();
	}

	/**
	 * @param int $id Row id.
	 * @return array|null
	 */
	public static function row( $id ) {
		global $wpdb;
		$table = self::table();
		$r     = $wpdb->get_row( $wpdb->prepare( "SELECT * FROM $table WHERE id = %d", (int) $id ), ARRAY_A ); // phpcs:ignore WordPress.DB
		return $r ? self::hydrate( (array) $r ) : null;
	}
	/**
	 * @param int   $id     Row id.
	 * @param array $values Whitelisted columns.
	 * @return bool
	 */
	public static function update( $id, $values ) {
		global $wpdb;
		$allowed = array( 'title', 'keyword', 'secondary', 'intent', 'priority', 'reason', 'status', 'post_id', 'job_id', 'stage', 'error' );
		// These three hold structured state and are stored as JSON.
		$json_columns = array( 'brief' => 1, 'notes' => 1 );
		$set     = array();
		$forms   = array();
		foreach ( $json_columns as $key => $one ) {
			if ( array_key_exists( $key, $values ) ) {
				$set[ $key ]   = (string) wp_json_encode( (array) $values[ $key ], JSON_UNESCAPED_UNICODE );
				$forms[ $key ] = '%s';
			}
		}
		foreach ( $allowed as $key ) {
			if ( ! array_key_exists( $key, $values ) ) {
				continue;
			}
			if ( in_array( $key, array( 'priority', 'post_id', 'job_id' ), true ) ) {
				$set[ $key ]   = (int) $values[ $key ];
				$forms[ $key ] = '%d';
			} elseif ( 'status' === $key ) {
				if ( ! in_array( $values[ $key ], self::STATUSES, true ) ) {
					continue;
				}
				$set[ $key ]   = $values[ $key ];
				$forms[ $key ] = '%s';
			} elseif ( 'intent' === $key ) {
				$set[ $key ]   = in_array( $values[ $key ], self::INTENTS, true ) ? $values[ $key ] : 'informational';
				$forms[ $key ] = '%s';
			} else {
				$set[ $key ]   = sanitize_textarea_field( (string) $values[ $key ] );
				$forms[ $key ] = '%s';
			}
		}
		if ( ! $set ) {
			return false;
		}
		$set['updated']     = current_time( 'mysql' );
		$forms['updated']   = '%s';
		return false !== $wpdb->update( self::table(), $set, array( 'id' => (int) $id ), $forms, array( '%d' ) ); // phpcs:ignore WordPress.DB
	}
	/**
	 * @param int $id Row id.
	 * @return bool
	 */
	public static function delete( $id ) {
		global $wpdb;
		return (bool) $wpdb->delete( self::table(), array( 'id' => (int) $id ), array( '%d' ) ); // phpcs:ignore WordPress.DB
	}
	/**
	 * Rows per status, for the screen header.
	 *
	 * @return array<string,int>
	 */
	public static function counts() {
		global $wpdb;
		$table = self::table();
		$out   = array_fill_keys( self::STATUSES, 0 );
		foreach ( (array) $wpdb->get_results( "SELECT status, COUNT(*) AS c FROM $table GROUP BY status", ARRAY_A ) as $row ) { // phpcs:ignore WordPress.DB
			$status = (string) $row['status'];
			if ( isset( $out[ $status ] ) ) {
				$out[ $status ] = (int) $row['c'];
			}
		}
		return $out;
	}
	/* ------------------------------------------------------------------
	 * Cost control
	 * ---------------------------------------------------------------- */
	/**
	 * What one article will roughly cost, in tokens.
	 *
	 * A deliberate over-estimate rather than a clever one: the input side is the
	 * site profile, the retrieved context and the instruction block, and Persian
	 * tokenises worse than English. Under-estimating is what turns a "safe"
	 * batch into a surprise bill.
	 *
	 * Since D3 the planner path is the *staged* pipeline — outline, then one
	 * call per section, then meta — so the staged cost wins whenever it is
	 * larger. Quoting the old one-call figure here would understate reality by
	 * the number of sections.
	 *
	 * @param int    $articles How many.
	 * @param bool   $with_image Count one extra call per article.
	 * @return int
	 */
	public static function estimate_tokens( $articles = 1, $with_image = false ) {
		$words = Haa_Util::length_words( (string) Haa_Settings::get( 'content.default_length', 'medium' ) );
		$oneshot = (int) ceil( $words * 2.0 ) + 1500;

		$staged = (int) Haa_Pipeline::cost_of( (array) Haa_Settings::get( 'article', array() ) )['tokens'];

		$per    = max( $oneshot, $staged );
		$images = $with_image ? 700 : 0;
		return max( 0, (int) $articles ) * ( $per + $images );
	}

	/**
	 * Model calls one article will cost, for the same reason as above.
	 *
	 * @param int  $articles    How many.
	 * @param bool $with_image  One extra per article.
	 * @return int
	 */
	public static function estimate_requests( $articles = 1, $with_image = false ) {
		$cost = Haa_Pipeline::cost_of( (array) Haa_Settings::get( 'article', array() ) );
		return max( 0, (int) $articles ) * ( (int) $cost['calls'] + ( $with_image ? 1 : 0 ) );
	}

	/**
	 * @param int $articles How many articles.
	 * @return array{articles:int,requests:int,tokens:int,cap:int,left:int,blocked:string,calls:int}
	 */
	public static function estimate( $articles, $with_image = false ) {
		$articles = max( 0, (int) $articles );
		$cap      = (int) Haa_Settings::get( 'article.daily_token_cap', 200000 );
		$used     = Haa_Usage::tokens_today();
		return array(
			'articles' => $articles,
			'requests' => self::estimate_requests( $articles, $with_image ),
			'calls'    => (int) Haa_Pipeline::cost_of( (array) Haa_Settings::get( 'article', array() ) )['calls'],
			'tokens'   => self::estimate_tokens( $articles, $with_image ),
			'cap'      => $cap,
			'left'     => $cap > 0 ? max( 0, $cap - $used ) : 0,
			'blocked'  => ( $cap > 0 && ( $used + self::estimate_tokens( max( 1, $articles ), $with_image ) ) > $cap )
				? __( 'با سقف توکن روزانه‌ی شما نمی‌گنجد؛ یا سقف را بالا ببرید یا تعداد را کم کنید.', 'hami-ai-assistant' )
				: '',
		);
	}
	/**
	 * How many articles still fit inside the daily token ceiling.
	 *
	 * @param bool $with_image Same per-article extra as the estimate uses.
	 * @return int PHP_INT_MAX when no ceiling is set.
	 */
	public static function room_in_tokens( $with_image = false ) {
		$cap  = (int) Haa_Settings::get( 'article.daily_token_cap', 200000 );
		if ( $cap <= 0 ) {
			return PHP_INT_MAX;
		}
		$left = max( 0, $cap - (int) Haa_Usage::tokens_today() );
		$one  = max( 1, self::estimate_tokens( 1, $with_image ) );
		return (int) floor( $left / $one );
	}

	/**
	 * How many articles may still be queued today.
	 *
	 * @return int
	 */
	public static function room_today() {
		$cap    = (int) Haa_Settings::get( 'article.daily_article_cap', 5 );
		$today  = (int) Haa_Usage::generated_posts_today();
		return $cap > 0 ? max( 0, $cap - $today ) : PHP_INT_MAX;
	}
	/**
	 * Queue approved rows through the existing article job.
	 *
	 * Caps are re-checked here rather than trusted from the browser: this is the
	 * only place where money is actually committed.
	 *
	 * @param array<int> $ids Row ids.
	 * @param array      $args tone, length, category, with_image.
	 * @return array{queued:int,skipped:int,reason:string,estimate:array}
	 */
	public static function queue( $ids, $args = array() ) {
		$ids   = array_values( array_filter( array_map( 'absint', (array) $ids ) ) );
		$cap   = self::estimate( count( $ids ) );
		$with_image = ! empty( $args['with_image'] );

		// Two independent ceilings: articles per day and tokens per day. A staged
		// article costs several calls, so the token side usually binds first — and
		// refusing the whole batch over that would be rude. Whatever fits is
		// queued and the rest is left with a reason.
		$room   = min( self::room_today(), self::room_in_tokens( $with_image ) );
		$room   = ( $room >= PHP_INT_MAX ) ? PHP_INT_MAX : max( 0, (int) $room );

		if ( ! $ids ) {
			return array( 'queued' => 0, 'skipped' => 0, 'reason' => __( 'موضوعی انتخاب نشده است.', 'hami-ai-assistant' ), 'estimate' => $cap );
		}
		if ( $room <= 0 ) {
			return array(
				'queued'    => 0,
				'skipped'   => count( $ids ),
				'reason'    => __( 'سقف توکن یا مقاله‌ی امروز پر شده است؛ با «نیازمند تأیید» فردا ادامه دهید یا سقف را بالا ببرید.', 'hami-ai-assistant' ),
				'estimate'  => $cap,
			);
		}
		if ( $room < count( $ids ) ) {
			$cap['blocked'] = sprintf(
				/* translators: 1: room, 2: asked. */
				__( 'فقط %1$d موضوع از %2$d مورد امروز جا می‌شود؛ بقیه صف نمی‌شوند.', 'hami-ai-assistant' ),
				$room,
				count( $ids )
			);
		}
		$queued  = 0;
		$skipped = 0;
		foreach ( $ids as $id ) {
			if ( $queued >= $room ) {
				$skipped++;
				continue;
			}
			$row = self::row( $id );
			if ( ! $row || ! in_array( $row['status'], array( 'suggested', 'approved' ), true ) ) {
				$skipped++;
				continue;
			}
			$job = Haa_Queue::push(
				'aw_article',
				array(
					'topic'    => (string) $row['title'],
					'keyword'  => (string) $row['keyword'],
					'intent'   => (string) $row['intent'],
					'tone'     => $args['tone'] ?? '',
					'length'   => $args['length'] ?? '',
					'category' => (int) ( $args['category'] ?? 0 ),
					// Same key the manual queue form uses, so the job has one
					// spelling for it.
					'image'    => ! empty( $args['with_image'] ),
					'topic_id' => (int) $row['id'],
				),
				array( 'module' => 'article-writer' )
			);
			if ( $job ) {
				self::update(
					$id,
					array(
						'status' => 'queued',
						'job_id' => (int) $job,
					)
				);
				$queued++;
			} else {
				$skipped++;
			}
		}
		return array(
			'queued'   => $queued,
			'skipped'  => $skipped,
			'reason'   => $skipped ? sprintf( /* translators: %d: count. */ __( '%d موضوع صف نشد (تکراری، ردشده یا سقف روزانه).', 'hami-ai-assistant' ), $skipped ) : '',
			'estimate' => self::estimate( $queued, ! empty( $args['with_image'] ) ),
		);
	}
	/**
	 * Called once the article exists, so the planner stops proposing it again.
	 *
	 * @param int $topic_id Row id.
	 * @param int $post_id  Written post id.
	 * @return void
	 */
	public static function mark_published( $topic_id, $post_id ) {
		if ( ! $topic_id ) {
			return;
		}
		self::update(
			(int) $topic_id,
			array(
				'status'  => 'published',
				'post_id' => (int) $post_id,
			)
		);
		self::flush_map();
	}
