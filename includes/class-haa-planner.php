<?php
/**
 * SEO planner — what the site already covers, what it does not, and what to
 * write next.
 *
 * Three jobs, in this order:
 *
 *  1. Read the site's own index (the knowledge base the semantic-search module
 *     already built) and lay it out as a topical map.
 *  2. Find the holes: categories and clusters with no article, and topics that
 *     would merely repeat something already published.
 *  3. Propose subjects — first without spending anything (derived from the
 *     holes), optionally once with the model — and hold them in a table until a
 *     human approves, edits or drops them.
 *
 * Nothing here runs on a public page. Every query is bounded, the site map is
 * cached, and the model is asked at most once per planning run.
 *
 * @package Hami_AI_Assistant
 */
if ( ! defined( 'ABSPATH' ) ) {
	exit;
}
final class Haa_Planner {
	/** Map cache lifetime; the index itself only moves when content changes. */
	const MAP_CACHE = 'haai_planner_map';
	const MAP_TTL   = 900;
	/** Search intents, kept in English in the DB and translated in the UI. */
	const INTENTS = array( 'informational', 'commercial', 'transactional' );
	const STATUSES = array( 'suggested', 'approved', 'queued', 'rejected', 'published' );
	/**
	 * Table name.
	 *
	 * @return string
	 */
	public static function table() {
		return Haa_DB::table( 'topics' );
	}
	/** @return string */
	public static function intent_label( $slug ) {
		$labels = array(
			'informational' => __( 'اطلاعاتی', 'hami-ai-assistant' ),
			'commercial'    => __( 'تجاری (مقایسه/بررسی)', 'hami-ai-assistant' ),
			'transactional' => __( 'تراکنشی (آماده خرید)', 'hami-ai-assistant' ),
		);
		return isset( $labels[ $slug ] ) ? $labels[ $slug ] : $slug;
	}
	/* ------------------------------------------------------------------
	 * 1. The site's own map
	 * ---------------------------------------------------------------- */
	/**
	 * Topical map built from the knowledge-base index.
	 *
	 * @return array{sources:array,intents:array,terms:array,posts:int,generated:int}
	 */
	public static function site_map( $fresh = false ) {
		if ( ! $fresh ) {
			$cached = get_transient( self::MAP_CACHE );
			if ( is_array( $cached ) ) {
				return $cached;
			}
		}
		global $wpdb;
		$topics = self::table();
		$chunks = Haa_DB::table( 'chunks' );
		$by_source = $wpdb->get_results( "SELECT source, COUNT(DISTINCT post_id) AS items, COUNT(*) AS chunks FROM $chunks GROUP BY source", ARRAY_A ); // phpcs:ignore WordPress.DB
		$sources = array();
		foreach ( (array) $by_source as $row ) {
			$sources[ (string) $row['source'] ] = array(
				'items'  => (int) $row['items'],
				'chunks' => (int) $row['chunks'],
			);
		}
		// Titles per source, the raw material for both the term list and the
		// duplicate check below.
		$titles = $wpdb->get_results( "SELECT post_id, title, source FROM $chunks WHERE title <> '' GROUP BY post_id, source ORDER BY id DESC LIMIT 400", ARRAY_A ); // phpcs:ignore WordPress.DB
		$terms  = array();
		$posts  = array();
		foreach ( (array) $titles as $row ) {
			$posts[ (int) $row['post_id'] ] = (string) $row['title'];
			foreach ( Haa_Search::tokenize( (string) $row['title'] ) as $word ) {
				if ( mb_strlen( $word ) < 3 ) {
					// Single letters and two-letter fragments are noise; three is
					// where real Persian content words start (کفش, کیف, توپ).
					continue;
				}
				$terms[ $word ] = ( isset( $terms[ $word ] ) ? $terms[ $word ] : 0 ) + 1;
			}
		}
		arsort( $terms );
		$terms = array_slice( $terms, 0, 60, true );
		// How many of the site's own articles were generated by us, so the
		// dashboard can tell "we wrote this" apart from "the site had this".
		$generated = 0;
		$table     = $wpdb->posts;
		if ( $wpdb->get_var( $wpdb->prepare( 'SHOW TABLES LIKE %s', $wpdb->esc_like( $table ) ) ) ) { // phpcs:ignore WordPress.DB
			$generated = (int) $wpdb->get_var( "SELECT COUNT(*) FROM $table WHERE post_type = 'post' AND post_status IN ('draft','pending','publish') AND ID IN (SELECT post_id FROM $topics WHERE status = 'published' AND post_id > 0)" ); // phpcs:ignore WordPress.DB
		}
		$map = array(
			'sources'   => $sources,
			'intents'   => self::clusters( $titles ),
			'terms'     => $terms,
			'posts'     => count( $posts ),
			'generated' => $generated,
			'titles'    => $posts,
		);
		set_transient( self::MAP_CACHE, $map, self::MAP_TTL );
		return $map;
	}
	/**
	 * Drop the cached map, e.g. after publishing something new.
	 *
	 * @return void
	 */
	public static function flush_map() {
		delete_transient( self::MAP_CACHE );
	}
	/**
	 * Group indexed documents by the category they belong to.
	 *
	 * Products count in their own product_cat, not in one lump: "we have 40
	 * products and no article about any of them" is the single most useful thing
	 * this map can tell an editor, and a single 'products' bucket hides it.
	 *
	 * @param array $rows Indexed title rows.
	 * @return array<string,array{items:int,titles:array}>
	 */
	public static function clusters( $rows ) {
		$out = array();
		foreach ( (array) $rows as $row ) {
			$pid = (int) $row['post_id'];
			$cat = self::content_category( $pid );
			if ( ! isset( $out[ $cat ] ) ) {
				$out[ $cat ] = array( 'items' => 0, 'titles' => array() );
			}
			$out[ $cat ]['items']++;
			if ( count( $out[ $cat ]['titles'] ) < 8 ) {
				$out[ $cat ]['titles'][] = (string) $row['title'];
			}
		}
		ksort( $out );
		return $out;
	}
	/**
	 * The category a document is filed under, blog or shop side.
	 *
	 * @param int $post_id Post id.
	 * @return string
	 */
	public static function content_category( $post_id ) {
		foreach ( array( 'category', 'product_cat' ) as $tax ) {
			$terms = get_the_terms( (int) $post_id, $tax );
			if ( $terms && ! is_wp_error( $terms ) ) {
				$first = (array) $terms;
				if ( isset( $first[0]->name ) && '' !== (string) $first[0]->name ) {
					return (string) $first[0]->name;
				}
			}
		}
		return __( 'بدون دسته', 'hami-ai-assistant' );
	}
	/**
	 * Clusters that hold products or pages but no article, i.e. where writing
	 * something new actually has a place to link to.
	 *
	 * @return array<int,array{cluster:string,items:int,articles:int}>
	 */
	public static function gaps() {
		$map   = self::site_map();
		$posts = self::published_articles();
		$out = array();
		foreach ( $map['intents'] as $name => $cluster ) {
			$articles = 0;
			foreach ( $posts as $post ) {
				if ( self::content_category( $post['id'] ) === $name ) {
					$articles++;
				}
			}
			if ( 0 === $articles ) {
				$out[] = array(
					'cluster'  => $name,
					'items'    => (int) $cluster['items'],
					'articles' => 0,
				);
			}
		}
		usort( $out, function ( $a, $b ) { return $b['items'] - $a['items']; } );
		return $out;
	}
	/**
	 * Real blog posts, whatever their status.
	 *
	 * Memoised per request: the planner compares every proposal against every
	 * existing post, and without this a 50-row screen would run 50 identical
	 * 300-post queries.
	 *
	 * @return array<int,array{id:int,title:string}>
	 */
	public static function published_articles( $fresh = false ) {
		static $cache = null;
		if ( null !== $cache && ! $fresh ) {
			return $cache;
		}
			$out  = array();
		$seen = array();
		foreach ( (array) get_posts(
			array(
				'post_type'      => 'post',
				'post_status'    => array( 'publish', 'draft', 'pending', 'future' ),
				'posts_per_page' => 300,
				'fields'         => 'ids',
			)
		) as $id ) {
			$id = (int) $id;
			if ( isset( $seen[ $id ] ) ) {
				continue;
			}
			$seen[ $id ]  = 1;
			$out[ $id ]   = array( 'id' => $id, 'title' => get_the_title( $id ) );
		}
			$cache = $out;
			return $cache;
	}
	/* ------------------------------------------------------------------
	 * 2. Competition with what already exists
	 * ---------------------------------------------------------------- */
	/**
	 * Would this subject repeat something the site already published?
	 *
	 * Two independent guards, because each catches what the other misses:
	 * a title that is nearly the same words in another order (token overlap),
	 * and a title that is genuinely different but about the same thing
	 * (the hybrid index score, when the semantic-search module is on).
	 *
	 * @param string $title Proposed title.
	 * @param string $keyword Main keyword.
	 * @return array{duplicate:bool,score:float,post_id:int,title:string,via:string}
	 */
	public static function competition( $title, $keyword = '' ) {
		$threshold = (float) Haa_Settings::get( 'article.dup_threshold', 0.7 );
		$best      = array(
			'duplicate' => false,
			'score'     => 0.0,
			'post_id'   => 0,
			'title'     => '',
			'via'       => '',
		);
		$tokens = self::token_set( $title . ' ' . $keyword );
		foreach ( self::published_articles() as $post ) {
			$score = self::overlap( $tokens, self::token_set( $post['title'] ) );
			if ( $score > $best['score'] ) {
				$best = array(
					'duplicate' => $score >= $threshold,
					'score'     => round( $score, 3 ),
					'post_id'   => (int) $post['id'],
					'title'     => (string) $post['title'],
					'via'       => 'title',
				);
			}
		}
		// The index can say "different words, same subject" — only if it exists.
		if ( ! $best['duplicate'] && Haa_Settings::is_module_enabled( 'semantic-search' ) ) {
			foreach ( Haa_Search::search( $title . ' ' . $keyword, 3, 200 ) as $hit ) {
				$score = min( 1.0, (float) ( $hit['score'] ?? 0 ) );
				if ( $score > $best['score'] ) {
					$best = array(
						'duplicate' => $score >= $threshold,
						'score'     => round( $score, 3 ),
						'post_id'   => (int) ( $hit['post_id'] ?? 0 ),
						'title'     => (string) ( $hit['title'] ?? '' ),
						'via'       => 'index',
					);
				}
			}
		}
		return $best;
	}
	/**
	 * Is the same subject already sitting in the planner, unapproved or not?
	 *
	 * @param string $title Proposed title.
	 * @return int Existing row id, 0 when new.
	 */
	public static function existing_topic( $title ) {
		global $wpdb;
		$table = self::table();
		$found = $wpdb->get_var( $wpdb->prepare( "SELECT id FROM $table WHERE title = %s LIMIT 1", $title ) ); // phpcs:ignore WordPress.DB
		return (int) $found;
	}
	/** @return array<string,int> */
	private static function token_set( $text ) {
		$out = array();
		foreach ( Haa_Search::tokenize( (string) $text ) as $word ) {
			$out[ $word ] = 1;
		}
		return $out;
	}
	/**
	 * Jaccard overlap of two token sets.
	 *
	 * @return float 0..1
	 */
	private static function overlap( $a, $b ) {
		if ( ! $a || ! $b ) {
			return 0.0;
		}
		$both = count( array_intersect_key( $a, $b ) );
		$all  = count( $a + $b );
		return $all ? $both / $all : 0.0;
	}
	/* ------------------------------------------------------------------
	 * 3. Proposals, and the table that holds them
	 * ---------------------------------------------------------------- */
	/**
	 * Clean and validate one proposed row.
	 *
	 * @param array $raw Row from the model or from a gap.
	 * @return array|null Null when the row is unusable.
	 */
	public static function sanitize_row( $raw ) {
		$title = sanitize_text_field( (string) ( $raw['title'] ?? '' ) );
		if ( '' === $title || mb_strlen( $title ) < 8 ) {
			return null;
		}
		$intent = sanitize_key( (string) ( $raw['intent'] ?? 'informational' ) );
		if ( ! in_array( $intent, self::INTENTS, true ) ) {
			$intent = 'informational';
		}
		return array(
			'title'     => Haa_Util::cut( $title, 200 ),
			'keyword'   => Haa_Util::cut( sanitize_text_field( (string) ( $raw['keyword'] ?? '' ) ), 160 ),
			'secondary' => Haa_Util::cut( sanitize_text_field( (string) ( $raw['secondary'] ?? '' ) ), 200 ),
			'intent'    => $intent,
			'priority'  => max( 1, min( 9, (int) ( $raw['priority'] ?? 5 ) ) ),
			'reason'    => sanitize_textarea_field( (string) ( $raw['reason'] ?? '' ) ),
			'source'    => in_array( (string) ( $raw['source'] ?? '' ), array( 'gap', 'model', 'manual' ), true ) ? (string) $raw['source'] : 'manual',
		);
	}
	/**
	 * Insert a proposal unless it repeats a row already in the planner.
	 *
	 * @param array $row sanitize_row() output.
	 * @return int Row id, 0 when skipped.
	 */
	public static function insert( $row ) {
		global $wpdb;

		// sanitize_row() only knows the editorial columns, so the structured ones
		// are taken from the raw input first — otherwise a caller passing a brief
		// here would lose it without any error.
		$raw   = is_array( $row ) ? $row : array();
		$brief = isset( $raw['brief'] ) && is_array( $raw['brief'] ) && $raw['brief'] ? $raw['brief'] : array();
		$stage = isset( $raw['stage'] ) ? (string) $raw['stage'] : '';

		$row = self::sanitize_row( $row );
		if ( ! $row || self::existing_topic( $row['title'] ) ) {
			return 0;
		}
		$table = self::table();
		$now   = current_time( 'mysql' );
		$done = $wpdb->insert( // phpcs:ignore WordPress.DB.DirectDatabaseQuery
			$table,
			array_merge(
				$row,
				array(
					'status'     => 'suggested',
					'post_id'    => 0,
					'job_id'     => 0,
					'tokens_est' => self::estimate_tokens( 1 ),
					'created'    => $now,
					'updated'    => $now,
				)
			),
			array( '%s', '%s', '%s', '%s', '%d', '%s', '%s', '%d', '%s', '%s' )
		);

		$id = $done ? (int) $wpdb->insert_id : 0;
		if ( $id && ( $brief || '' !== $stage ) ) {
			$carry = array();
			if ( $brief ) {
				$carry['brief'] = $brief;
			}
			if ( '' !== $stage ) {
				$carry['stage'] = $stage;
			}
			self::update( $id, $carry );
		}

		return $id;
	}
	/**
	 * Proposals derived from the holes in the current content. Costs nothing.
	 *
	 * @param int $count How many at most.
	 * @return array<int,array{added:int,skipped:int,reason:string}>
	 */
	public static function propose_from_gaps( $count = 6 ) {
		$count = max( 1, min( 20, (int) $count ) );
		$added = 0;
		$skipped = 0;
		foreach ( self::gaps() as $gap ) {
			if ( $added >= $count ) {
				break;
			}
			foreach ( self::gap_rows( $gap ) as $row ) {
				if ( $added >= $count ) {
					break;
				}
				if ( self::competition( $row['title'], $row['keyword'] )['duplicate'] ) {
					$skipped++;
					continue;
				}
				if ( self::insert( $row ) ) {
					$added++;
				} else {
					$skipped++;
				}
			}
		}
		return array(
			'added'   => $added,
			'skipped' => $skipped,
			'reason'  => $added ? '' : __( 'خوشه‌ی بدون مقالاتی نمانده که برایش موضوع تازه‌ای ساخته شود.', 'hami-ai-assistant' ),
		);
	}

	/**
	 * Insert caller-supplied topic rows, with the same de-duplication every
	 * other source goes through. Free: no model call.
	 *
	 * Used by the competitor-gap picker in D2, which hands over headings only.
	 *
	 * @param array<int,array> $rows Candidate rows.
	 * @return array{added:int,skipped:int,reason:string}
	 */
	public static function propose_from_rows( $rows ) {
		$added   = 0;
		$skipped = 0;

		foreach ( (array) $rows as $row ) {
			if ( ! is_array( $row ) ) {
				$skipped++;
				continue;
			}
			$clean = self::sanitize_row( $row );
			if ( '' === $clean['title'] ) {
				$skipped++;
				continue;
			}
			if ( self::competition( $clean['title'], $clean['keyword'] )['duplicate'] ) {
				$skipped++;
				continue;
			}
			if ( self::insert( $clean ) ) {
				$added++;
			} else {
				$skipped++;
			}
		}

		return array(
			'added'   => $added,
			'skipped' => $skipped,
			'reason'  => $added ? '' : __( 'همه‌ی گزینه‌ها با محتوای موجود تکراری بودند.', 'hami-ai-assistant' ),
		);
	}
