	/**
	 * One model call for a subject list, only on an explicit request.
	 *
	 * The prompt carries the site profile, the topical map and the words the
	 * site already uses, and is told plainly that it has no access to search
	 * results or volume data — so it proposes from context instead of inventing
	 * keywords that look authoritative.
	 *
	 * @param int $count How many at most.
	 * @return array{ok:bool,error?:string,added:int,skipped:int}
	 */
	public static function propose_with_model( $count = 6 ) {
		$count = max( 1, min( 20, (int) $count ) );
		$map   = self::site_map();
		$terms = array();
		foreach ( array_keys( $map['terms'] ) as $word ) {
			$terms[] = $word;
			if ( count( $terms ) >= 30 ) {
				break;
			}
		}
		$clusters = array_keys( $map['intents'] );
		$system = __( 'تو برنامه‌ریز محتوای سئو برای یک سایت فارسی‌زبان هستی.', 'hami-ai-assistant' ) . "\n"
			. __( 'خروجی فقط یک آرایه‌ی JSON با همین کلیدها باشد، بدون متن اضافه و بدون کد فنس:', 'hami-ai-assistant' ) . "\n"
			. '[{"title":"…","keyword":"…","secondary":"…","intent":"informational|commercial|transactional","priority":1,"reason":"…"}]' . "\n"
			. Haa_Content::no_fabrication() . "\n"
			. '- ' . __( 'به داده‌ی جست‌وجوی گوگل، حجم سرچ یا ترند دسترسی نداری؛ ادعای عددی درباره‌شان نساز.', 'hami-ai-assistant' ) . "\n"
			. '- ' . sprintf( /* translators: %d: number of topics. */ __( 'دقیقاً %d موضوع پیشنهاد بده.', 'hami-ai-assistant' ), $count ) . "\n"
			. '- ' . __( 'reason باید بگوید چرا این موضوع برای همین سایت سودمند است، نه یک جمله‌ی کلی.', 'hami-ai-assistant' ) . "\n"
			. '- ' . __( 'عنوان‌ها را با تیترهای موجود روی سایت تکرار نکن.', 'hami-ai-assistant' );
		$profile = Haa_Site_Profile::block( '');
		$user    = ( $profile ? $profile . "\n\n" : '' )
			. __( 'خوشه‌های محتوایی فعلی سایت:', 'hami-ai-assistant' ) . ' ' . implode( '، ', array_slice( $clusters, 0, 20 ) ) . "\n"
			. __( 'واژه‌های پرتکرار تیترهای سایت:', 'hami-ai-assistant' ) . ' ' . implode( '، ', $terms ) . "\n"
			. __( 'تیترهای موجود (تکرار نکن):', 'hami-ai-assistant' ) . ' ' . implode( ' | ', array_slice( array_values( $map['titles'] ), 0, 25 ) ) . "\n"
			. __( 'حالا موضوع‌های پیشنهادی را بنویس.', 'hami-ai-assistant' );
		$raw = Haa_Content::generate( $system, $user, array( 'module' => 'article-writer', 'operation' => 'planner' ) );
		if ( is_wp_error( $raw ) ) {
			return array(
				'ok'      => false,
				'added'   => 0,
				'skipped' => 0,
				'error'   => (string) $raw->get_error_message(),
			);
		}
		$rows  = Haa_Util::extract_json( $raw );
		// extract_json hands back whatever it found; a single object is still a
		// usable one-row answer.
		if ( isset( $rows['title'] ) ) {
			$rows = array( $rows );
		}
		$added = 0;
		$skipped = 0;
		foreach ( (array) $rows as $row ) {
			$row = self::sanitize_row( is_array( $row ) ? (array) $row + array( 'source' => 'model' ) : array() );
			if ( ! $row ) {
				$skipped++;
				continue;
			}
			$comp = self::competition( $row['title'], $row['keyword'] );
			if ( $comp['duplicate'] || ! self::insert( $row ) ) {
				$skipped++;
				continue;
			}
			$added++;
		}
		return array( 'ok' => true, 'added' => $added, 'skipped' => $skipped, 'error' => '' );
	}
